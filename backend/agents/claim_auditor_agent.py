import re
from typing import Dict, Any, List

def audit_claims(raw_facts: Dict[str, Any], ai_explanation: Dict[str, Any]) -> Dict[str, Any]:
    """
    Agent 4: AI Claim Auditor Agent
    Independently inspects every statement generated by the AI Explanation Agent against
    the deterministic facts and raw PayPal evidence.
    
    Responsibilities:
    - Verifies that every claim cites valid evidence IDs.
    - Validates amounts and currencies mentioned in claims.
    - Detects unsupported assumptions or hallucinations.
    - Filters out rejected claims with reasons.
    - Preserves deterministic verdict integrity.
    """
    valid_evidence_ids = {e["id"]: e for e in raw_facts.get("evidence", [])}
    raw_verdict = raw_facts["verdict"]
    
    supported_claims: List[str] = []
    rejected_claims: List[Dict[str, str]] = []

    # Audit each reason in the explanation
    reasons = ai_explanation.get("reasons", [])
    for reason in reasons:
        # Find citations like [E1], [E2]
        citations = re.findall(r"\[(E\d+)\]", reason)
        
        if not citations:
            # Check if reason mentions general facts
            # Without citation, flag as unsupported
            rejected_claims.append({
                "original_claim": reason,
                "verification_result": "REJECTED",
                "reason_for_rejection": "Claim does not cite any ground-truth evidence ID [E#]."
            })
            continue

        invalid_citations = [c for c in citations if c not in valid_evidence_ids]
        if invalid_citations:
            rejected_claims.append({
                "original_claim": reason,
                "verification_result": "REJECTED",
                "reason_for_rejection": f"Cites non-existent evidence IDs: {invalid_citations}"
            })
            continue

        # Check for currency or amount contradictions in reason text
        has_contradiction = False
        for cid in citations:
            ev_item = valid_evidence_ids[cid]
            # If evidence has a status or currency, check if text contradicts it
            ev_val = ev_item["value"].lower()
            if "status" in ev_item["field"] and ev_val == "completed" and "pending" in reason.lower() and raw_verdict == "SHIP":
                rejected_claims.append({
                    "original_claim": reason,
                    "verification_result": "REJECTED",
                    "reason_for_rejection": "Contradicts verified COMPLETED capture status."
                })
                has_contradiction = True
                break

        if not has_contradiction:
            supported_claims.append(reason)

    claims_removed_count = len(rejected_claims)
    
    # If all reasons were rejected, fallback to ground-truth rule reasons
    verified_reasons = supported_claims if supported_claims else [
        f"{f['reason']} [{f['evidence'][0]}]" for f in raw_facts.get("findings", []) if f.get("evidence")
    ]

    verified_explanation = dict(ai_explanation)
    verified_explanation["reasons"] = verified_reasons
    verified_explanation["verdict"] = raw_verdict  # Absolute enforcement

    verification_status = "PASSED" if claims_removed_count == 0 else "WARNING"

    return {
        "verified_explanation": verified_explanation,
        "supported_claims": supported_claims,
        "rejected_claims": rejected_claims,
        "claims_removed_count": claims_removed_count,
        "verification_status": verification_status,
        "audit_summary": f"Audited {len(reasons)} claims: {len(supported_claims)} verified, {claims_removed_count} rejected."
    }
